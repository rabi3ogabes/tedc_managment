    public function docx(string $markdown): string
    {
        $w = new DocxWriter(null);
        $lines = preg_split('/\R/u', $markdown) ?: [];
        $bullets = [];
        $table = [];
        $flush = function () use (&$bullets, &$table, $w) {
            if ($bullets) {
                $w->bullets($bullets);
                $bullets = [];
            }
            if ($table) {
                $head = array_shift($table);
                $w->table($head, $table);
                $table = [];
            }
        };
        foreach ($lines as $line) {
            $line = rtrim($line);
            if (preg_match('/^\|(.+)\|$/u', $line, $m)) {
                $cells = array_map(fn ($c) => $this->inline(trim($c)), preg_split('/(?<!\\\\)\|/u', $m[1]) ?: []);
                if (! preg_match('/^[\s:|-]+$/', $m[1])) {
                    $table[] = array_map(fn ($c) => str_replace('\\|', '|', $c), $cells);
                }

                continue;
            }
            if ($table) {
                $flush();
            }
            if (preg_match('/^(#{1,6})\s+(.*)$/u', $line, $m)) {
                $flush();
                $w->heading($this->inline($m[2]), min(3, strlen($m[1])));
            } elseif (preg_match('/^\s*(?:[-*]|\d+\.)\s+(.*)$/u', $line, $m)) {
                $bullets[] = $this->inline($m[1]);
            } elseif (trim($line) === '') {
                $flush();
            } else {
                $flush();
                $w->text($this->inline(ltrim($line, "> \t")));
            }
        }
        $flush();

        return $w->bytes();
    }

    private function inline(string $t): string
    {
        return trim(preg_replace(['/\*\*(.+?)\*\*/u', '/`([^`]+)`/u', '/\[([^\]]+)\]\([^)]+\)/u', '/(?<![\w*])_(.+?)_(?![\w*])/u'], ['$1', '$1', '$1', '$1'], $t) ?? $t);
    }

    public function pdf(string $markdown, string $title): string
    {
        $env = new Environment([]);
        $env->addExtension(new CommonMarkCoreExtension);
        $env->addExtension(new GithubFlavoredMarkdownExtension);
        $html = (new MarkdownConverter($env))->convert($markdown)->getContent();
        // Bilingual text: every block that starts with Arabic is laid out right to left.
        $html = preg_replace_callback('~<(p|h[1-6]|li|td|th|blockquote)>(.*?)(?=</\1>)~su', function ($m) {
            $rtl = preg_match('/\p{Arabic}/u', mb_substr(strip_tags($m[2]), 0, 30)) === 1;

            return '<'.$m[1].($rtl ? ' dir="rtl" style="text-align:right"' : '').'>'.$m[2];
        }, $html) ?? $html;
        $theme = app(ThemeService::class);
        $center = $theme->centerName();
        $doc = '<html><head><meta charset="utf-8"><style>body{font-family:dejavusans;font-size:10pt;color:#1b2433}h1{font-size:20pt;color:#123b5d}h2{font-size:14pt;color:#123b5d;border-bottom:1pt solid #c9a24b}h3{font-size:11.5pt;color:#123b5d}table{border-collapse:collapse;width:100%;margin:6pt 0}td,th{border:.5pt solid #c8d0db;padding:3pt;font-size:8.5pt;vertical-align:top}th{background:#eef2f6}blockquote{border-left:3pt solid #c9a24b;margin:4pt 0;padding-left:6pt;color:#3a4658}code{font-size:8.5pt;background:#f3f5f8}</style></head><body>'.$html.'</body></html>';
        $mpdf = new Mpdf(['mode' => 'utf-8', 'format' => 'A4', 'margin_left' => 14, 'margin_right' => 14, 'margin_top' => 16, 'margin_bottom' => 16, 'default_font' => 'dejavusans', 'tempDir' => storage_path('app/mpdf'), 'autoScriptToLang' => true, 'autoLangToFont' => true]);
        $mpdf->SetTitle($title);
        $mpdf->SetFooter((is_array($center) ? ($center['en'] ?? '') : (string) $center).' · '.$title.' · {PAGENO}/{nbpg}');
        $mpdf->WriteHTML($doc);

        return $mpdf->Output('', 'S');
    }
}
